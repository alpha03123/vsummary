"""学习计划的 LLM 提示词。

天数、每天看哪几段、每段的时间都由代码按每日时长切好；模型只负责给每一课写
标题、目标、重点和练习，以及整份计划的概述和前置知识。
"""

STUDY_PLAN_PROMPT_TEMPLATE = (
    "下面是一份已经按每天 {daily_minutes} 分钟切好的学习安排，共 {session_count} 课。"
    "每课要看的片段、时长都已经定了，不要改动分课，也不要合并或拆分。\n"
    "请为每一课写学习内容，再写整份计划的概述和前置知识，只输出 JSON。\n\n"
    "要求：\n"
    "1. sessions 必须正好 {session_count} 项，index 与输入一一对应。\n"
    "2. title：这一课学什么，12 字以内，不要写“第几天”。\n"
    "3. goal：学完这一课应该会什么，一句话，写成能检验的能力，例如“能独立写出带参数的装饰器”。\n"
    "4. focus：2 到 4 条，这一课最该看懂的点，每条一句，具体到概念或步骤。\n"
    "5. practice：1 到 3 条，看完马上能做的练习或自测问题。动手类内容给动手任务，概念类内容给自测问题，不要写“复习本课内容”这种空话。\n"
    "6. 后面的课需要用到前面的知识时，可以在 practice 里安排一道回顾前面内容的题。\n"
    "7. overview：两三句，说明这份计划从哪里学到哪里、学完能做什么。\n"
    "8. prerequisites：开始前最好已经掌握的知识，0 到 4 条；视频本身就从零讲起的话给空数组。\n"
    "9. 只依据给出的内容，不要编造视频里没有的知识点；语气平实，不要口号和鼓励语。\n\n"
    "输出 JSON 结构：\n"
    "{{\n"
    '  "overview": "...",\n'
    '  "prerequisites": ["..."],\n'
    '  "sessions": [\n'
    '    {{"index": 1, "title": "...", "goal": "...", "focus": ["..."], "practice": ["..."]}}\n'
    "  ]\n"
    "}}\n\n"
    "学习材料：{title}\n"
    "{context}\n"
    "分课安排 JSON：\n"
    "{sessions_json}\n"
)
